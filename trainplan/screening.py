"""Скринінг перед формуванням плану (крок 1 алгоритму, п. 2.4).
Загальні питання — за структурою опитувальника PAR-Q+; формулювання скорочено.
Система не ставить діагнозів: позитивна відповідь на загальне питання означає
рекомендацію звернутися до лікаря, локальні обмеження перетворюються на теги K_U."""

GENERAL_QUESTIONS = [
    'Чи казав вам лікар, що у вас є захворювання серця або підвищений артеріальний тиск?',
    'Чи відчуваєте ви біль у грудях у спокої, під час повсякденної діяльності або фізичного навантаження?',
    'Чи втрачали ви рівновагу через запаморочення або втрачали свідомість за останні 12 місяців?',
    'Чи діагностовано у вас інше хронічне захворювання (крім серцево-судинних)?',
    'Чи приймаєте ви ліки за рецептом від хронічного захворювання?',
    'Чи є у вас проблеми з кістками, суглобами або м’язами, які можуть посилитися через фізичну активність?',
    'Чи казав вам лікар, що фізична активність можлива лише під медичним наглядом?',
]

LOCAL_TAGS = {
    'плече': 'Біль або травма плечового суглоба',
    'поперек': 'Біль у попереку або травма хребта',
    'коліно': 'Біль або травма колінного суглоба',
}


def screen(general_answers: list[bool], local: list[str]) -> dict:
    """Повертає {'allowed': bool, 'contra': set, 'message': str}."""
    if any(general_answers):
        return dict(allowed=False, contra=set(),
                    message='Перед початком тренувань рекомендовано проконсультуватися з лікарем. '
                            'Система не формує план без медичного допуску.')
    contra = {t for t in local if t in LOCAL_TAGS}
    return dict(allowed=True, contra=contra, message='')
